package anki

import (
	"github.com/npcnixel/genanki-go"
)

// Deck represents an in-memory Anki deck ready to be written as a .apkg file.
type Deck struct {
	Name  string
	Cards []Card
}

// Card is a single note in an Anki deck.
type Card struct {
	Front string
	Back  string
}

// WriteAPKG serialises the deck into a valid Anki .apkg package at path.
// It uses the genanki-go library, which produces a collection database
// compatible with Anki's importer (schema 11 with a correctly-formed deck
// config).
func (d *Deck) WriteAPKG(path string) error {
	model := genanki.NewBasicModel(genanki.GenerateIntID(), d.Name)
	deck := genanki.NewDeck(genanki.GenerateIntID(), d.Name, "Generated by betterhomework")

	for _, c := range d.Cards {
		note := genanki.NewNote(model.ID, []string{c.Front, c.Back}, nil)
		deck.AddNote(note)
	}

	pkg := genanki.NewPackage([]*genanki.Deck{deck}).AddModel(model.Model)
	return pkg.WriteToFile(path)
}
